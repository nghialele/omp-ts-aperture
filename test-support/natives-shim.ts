/**
 * Test-only shim for `@oh-my-pi/pi-natives`.
 *
 * Importing the real package (indirectly, through pi-ai, pi-catalog, and
 * pi-coding-agent) loads the Rust `pi_natives` addon eagerly at module scope.
 * A machine without a built addon then cannot even import the extension, which
 * makes unit tests impossible on a plain checkout.
 *
 * The shim exports the same names so importers link, but every value is an
 * inert proxy: it throws only when native code is actually called. Unit tests
 * exercise routing, config, and catalog logic, none of which touch the addon.
 *
 * Wired in through `bunfig.toml` [test] preload, so a real omp session is
 * untouched (it uses the real package).
 */

const message =
  "@oh-my-pi/pi-natives is not built in this checkout; " +
  "run `bun --cwd=oh-my-pi/packages/natives run build` to enable native code.";

function unavailable(): unknown {
  const fn = (..._args: unknown[]) => {
    throw new Error(message);
  };
  return new Proxy(fn, {
    get(_target, key) {
      if (key === "then" || typeof key === "symbol" || key === "prototype") {
        return undefined;
      }
      throw new Error(`${message} (tried to read \`${String(key)}\`)`);
    },
    construct() {
      throw new Error(message);
    },
    apply() {
      throw new Error(message);
    },
  });
}

